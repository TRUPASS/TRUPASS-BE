-- 회원 탈퇴와 약관 동의 이력.

-- 탈퇴한 시각. 탈퇴하면 개인정보(이메일·이름·사진·닉네임·출생 연도·성별·관심사)를 지우고 이 값을 채운다.
-- 주문·서명 기록이 이 행을 가리킬 수 있어 행은 지우지 않는다.
ALTER TABLE users
    ADD COLUMN withdrawn_at TIMESTAMPTZ;

-- 약관 동의·철회 이력. 지우거나 고치지 않고 쌓기만 한다(광고성 정보 수신 동의·철회 처리 기록 포함).
-- user_agreements는 지금 상태, 이 테이블은 바뀐 기록이다. 값은 TermsType enum 이름이다.
CREATE TABLE user_agreement_histories
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    terms_type VARCHAR(32) NOT NULL,
    agreed     BOOLEAN     NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_user_agreement_histories_user_id ON user_agreement_histories (user_id, id);

-- 이력이 생기기 전에 받아 둔 동의를 첫 기록으로 옮긴다.
INSERT INTO user_agreement_histories (user_id, terms_type, agreed, changed_at)
SELECT user_id, terms_type, TRUE, agreed_at
FROM user_agreements
ORDER BY user_id, agreed_at, terms_type;
